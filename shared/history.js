// ---------------------------------------------------------------------------
//  История действий по модулям: что уже сделано, чтобы после обрыва не
//  начинать с нуля и не дёргать одно и то же дважды.
//
//  Лежит в chrome.storage.local, ключ «история»:
//    { unfollow: { ids: [...] }, reposts: { ids: [...] }, tweets: {...}, dms: {...} }
//  Каждый модуль чистит только свою запись.
//
//  Чтение и запись идут строго по очереди: история — один общий ключ, и два
//  одновременных «прочитал → добавил → записал» (например, отписка пишет id,
//  пока листание репостов пишет свои) затирали бы друг друга: последняя запись
//  возвращала бы состояние, прочитанное до чужой правки.
// ---------------------------------------------------------------------------
(() => {
  const КЛЮЧ = 'история';
  const МОДУЛИ = ['unfollow', 'reposts', 'quotes', 'likes', 'ghostlikes', 'tweets', 'dms'];
  // Тот же лимит, что в background/store.js: история — память о сделанном,
  // а не склад; глубже 20 000 id на модуль она только тормозит попап.
  const ЛИМИТ = 20000;

  const читатьВсё = () => new Promise(resolve => {
    try { chrome.storage.local.get(КЛЮЧ, данные => resolve((данные && данные[КЛЮЧ]) || {})); }
    catch (e) { resolve({}); }
  });

  const писатьВсё = все => new Promise(resolve => {
    try { chrome.storage.local.set({ [КЛЮЧ]: все }, () => resolve()); }
    catch (e) { resolve(); }
  });

  // Очередь операций: ни одна запись не начинается, пока не закончилась
  // предыдущая. Ошибка одного шага не рвёт очередь — иначе после первого же
  // сбоя хранилища все следующие вызовы повисли бы.
  let цепочка = Promise.resolve();
  const поочередно = работа => {
    const шаг = цепочка.then(работа, работа);
    цепочка = шаг.then(() => undefined, () => undefined);
    return шаг;
  };

  // Старый формат — просто массив id вместо { ids, ts }: читаем и его,
  // иначе первая же запись потеряла бы историю, сохранённую прошлой версией.
  const idsМодуля = (все, модуль) => {
    const запись = все[модуль];
    if (Array.isArray(запись)) return запись.map(String);
    return ((запись && запись.ids) || []).map(String);
  };

  const прочитать = модуль => поочередно(async () => idsМодуля(await читатьВсё(), модуль));

  const добавить = (модуль, ids) => поочередно(async () => {
    const все = await читатьВсё();
    const набор = new Set(idsМодуля(все, модуль));
    (ids || []).map(String).forEach(id => набор.add(id));
    const список = [...набор];
    все[модуль] = { ids: список.length > ЛИМИТ ? список.slice(-ЛИМИТ) : список, ts: Date.now() };
    await писатьВсё(все);
    return [...набор];
  });

  const очистить = модуль => поочередно(async () => {
    const все = await читатьВсё();
    delete все[модуль];
    await писатьВсё(все);
    return [];
  });

  const всё = () => поочередно(async () => {
    const все = await читатьВсё();
    const итог = {};
    МОДУЛИ.forEach(м => { итог[м] = idsМодуля(все, м).length; });
    return итог;
  });

  window.XHistory = { КЛЮЧ, МОДУЛИ, ЛИМИТ, прочитать, добавить, очистить, всё };
})();
