// ---------------------------------------------------------------------------
//  Список «неприкасаемых» — общий для попапа и страницы.
//
//  Хранится в chrome.storage.local: { ники: [...], id: [...] }.
//  Умеет разбирать произвольный текст: ссылки x.com/twitter.com (в том числе
//  intent/follow?screen_name=), @ники, голые ники по строкам и числовые id.
//
//  Список — личное дело владельца браузера: расширение не подставляет в него
//  ничего от себя. В прежних версиях здесь лежал готовый список ников и флаг
//  «база внесена», из-за которого каждый новый пользователь получал чужой
//  список. Автоподстановку убрали; уже сохранённый у пользователя список
//  остаётся как есть — его никто не затирает.
// ---------------------------------------------------------------------------
(() => {
  const КЛЮЧ = 'защита';
  // Ключ остался от прежних версий: сам список тогда подмешивался из кода.
  // Теперь он только вычищается при первом чтении и больше ни на что не влияет.
  const СТАРЫЙ_ФЛАГ = 'защита_база_внесена';
  const СЛУЖЕБНЫЕ = new Set(['x', 'twitter', 'www', 'com', 'i', 'home', 'intent', 'follow', 'status', 'search', 'hashtag']);

  const пусто = () => ({ ники: [], id: [] });
  const норм = value => String(value || '').trim().toLowerCase();
  const какСписок = значение => (Array.isArray(значение) ? значение
    : (typeof значение === 'string' && значение.trim() ? [значение] : []));
  const уникально = arr => [...new Set(arr.map(x => String(x)).filter(Boolean))];

  /** Одна запись: @ник, ник, ссылка, числовой id. null — не распознано. */
  const разобратьЗапись = строка => {
    const raw = String(строка || '').trim();
    if (!raw) return null;

    if (/^\d{3,}$/.test(raw)) return { id: raw };

    const изСсылки = raw.match(/(?:https?:\/\/)?(?:www\.)?(?:x|twitter)\.com\/(?:intent\/follow\?screen_name=)?([A-Za-z0-9_]{1,15})/i);
    if (изСсылки) {
      const ник = изСсылки[1].toLowerCase();
      return СЛУЖЕБНЫЕ.has(ник) ? null : { ник };
    }

    const очищено = raw.replace(/^@/, '').trim();
    if (/^\d{3,}$/.test(очищено)) return { id: очищено };
    if (/^[A-Za-z0-9_]{1,15}$/.test(очищено)) {
      const ник = очищено.toLowerCase();
      return СЛУЖЕБНЫЕ.has(ник) ? null : { ник };
    }
    return null;
  };

  /** Произвольный текст → { ники, id }. */
  const разобратьТекст = текст => {
    const ники = [];
    const id = [];
    const push = запись => {
      if (!запись) return;
      if (запись.id) id.push(запись.id); else ники.push(запись.ник);
    };

    const body = String(текст || '');

    // ссылки: x.com/ник, twitter.com/ник, intent/follow?screen_name=ник
    const ссылки = body.match(/(?:https?:\/\/)?(?:www\.)?(?:x|twitter)\.com\/[^\s<>"')\]]+/gi) || [];
    ссылки.forEach(ссылка => push(разобратьЗапись(ссылка)));

    // @ники
    const собаки = body.match(/@[A-Za-z0-9_]{1,15}\b/g) || [];
    собаки.forEach(с => push(разобратьЗапись(с)));

    // голые ники и id — по строкам (строки с пробелами внутри не считаем)
    body.split(/[\r\n,;]+/).forEach(строка => {
      const token = строка.trim();
      if (!token || /\s/.test(token)) return;
      if (/^@/.test(token)) return;                 // уже разобрали
      if (/(?:x|twitter)\.com/i.test(token)) return; // уже разобрали
      push(разобратьЗапись(token));
    });

    return { ники: уникально(ники), id: уникально(id) };
  };

  // chrome.storage.local умеет и промисы, и колбэки; работаем через колбэки,
  // чтобы одинаково вести себя и в расширении, и в тестовых заглушках.
  const получить = keys => new Promise(resolve => {
    try { chrome.storage.local.get(keys, данные => resolve(данные || {})); }
    catch (e) { resolve({}); }
  });
  const записатьВХранилище = obj => new Promise(resolve => {
    try { chrome.storage.local.set(obj, () => resolve()); }
    catch (e) { resolve(); }
  });
  const убратьИзХранилища = keys => new Promise(resolve => {
    try { chrome.storage.local.remove(keys, () => resolve()); }
    catch (e) { resolve(); }
  });

  /** Только то, что сохранил сам пользователь. Пусто — значит пусто. */
  const прочитать = async () => {
    const данные = await получить([КЛЮЧ, СТАРЫЙ_ФЛАГ]);

    // Флаг от прежних версий больше не нужен: список не пополняется из кода.
    // Убираем его один раз, сам список не трогаем.
    if (данные[СТАРЫЙ_ФЛАГ] !== undefined) await убратьИзХранилища(СТАРЫЙ_ФЛАГ);

    const список = данные[КЛЮЧ];
    if (!список) return пусто();                    // первый запуск — ничего не пишем
    // Старый формат — массив или строка вместо { ники, id }: не теряем его.
    if (Array.isArray(список) || typeof список === 'string') {
      return { ники: какСписок(список).map(норм).filter(Boolean), id: [] };
    }
    return { ники: какСписок(список.ники).map(норм).filter(Boolean), id: какСписок(список.id).map(String) };
  };

  const записать = async список => {
    const нормализованный = {
      ники: уникально((список.ники || []).map(норм)),
      id: уникально((список.id || []).map(String))
    };
    await записатьВХранилище({ [КЛЮЧ]: нормализованный });
    return нормализованный;
  };

  /** Добавить из произвольного текста; возвращает { состояние, добавлено }. */
  const добавитьИзТекста = async текст => {
    const текущий = await прочитать();
    const найдено = разобратьТекст(текст);
    const было = new Set([...текущий.ники, ...текущий.id]);
    const новые = [...найдено.ники, ...найдено.id].filter(x => !было.has(x));
    const состояние = await записать({
      ники: [...текущий.ники, ...найдено.ники],
      id: [...текущий.id, ...найдено.id]
    });
    return { состояние, добавлено: новые.length, найдено: найдено.ники.length + найдено.id.length };
  };

  const удалить = async запись => {
    const текущий = await прочитать();
    const разобранная = разобратьЗапись(запись);
    if (!разобранная) return текущий;
    const состояние = await записать({
      ники: текущий.ники.filter(x => x !== разобранная.ник),
      id: текущий.id.filter(x => x !== разобранная.id)
    });
    return состояние;
  };

  const очистить = () => записать(пусто());

  window.XProtect = { КЛЮЧ, разобратьЗапись, разобратьТекст, прочитать, записать, добавитьИзТекста, удалить, очистить };
})();
