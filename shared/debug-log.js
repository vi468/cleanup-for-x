// ---------------------------------------------------------------------------
//  Журнал отладки для страницы. По умолчанию выключен.
//
//  Зачем: когда модуль что-то не удаляет, по одному «пропустил» не понять,
//  где сломалось — в разборе карточки, в истории или в ответе X. Журнал
//  складывает шаги в chrome.storage.local, а кнопка в панели отдаёт файлом.
//
//  Включается тумблером в панели модуля и живёт в chrome.storage.sync, чтобы
//  не собирать данные без спроса. Пока выключен, событие() ничего не пишет.
//
//  Чего здесь принципиально нет: cookie, токенов, заголовков, текстов твитов
//  и ников. Только id записи (он и так публичный), код ответа, короткий хвост
//  тела ответа X и счётчики очереди.
// ---------------------------------------------------------------------------
(() => {
  const КЛЮЧ_ЖУРНАЛА = 'журнал_вкладки';
  const КЛЮЧ_ФЛАГА = 'отладка';
  const ЛИМИТ = 300;
  const ДЛИНА = 300;

  let включён = false;

  // Тело ответа X иногда содержит куски запроса — вырезаем всё похожее на
  // секрет, даже если это ложное срабатывание.
  const чисто = значение => String(значение == null ? '' : значение)
    .replace(/(ct0|auth_token|authorization|cookie|bearer|token)([=:]\s*)[^\s,;"']+/gi, '$1$2***')
    .replace(/\s+/g, ' ')
    .slice(0, ДЛИНА);

  const флагЧитать = () => new Promise(готово => {
    try {
      chrome.storage.sync.get(КЛЮЧ_ФЛАГА, данные => готово(!!(данные && данные[КЛЮЧ_ФЛАГА])));
    } catch (e) { готово(false); }
  });

  флагЧитать().then(значение => { включён = значение; });

  try {
    chrome.storage.onChanged.addListener((изменения, область) => {
      if (область !== 'sync' || !изменения[КЛЮЧ_ФЛАГА]) return;
      включён = !!изменения[КЛЮЧ_ФЛАГА].newValue;
    });
  } catch (e) {}

  let цепочка = Promise.resolve();

  const событие = (имя, данные = {}) => {
    if (!включён) return цепочка;
    const запись = { t: new Date().toISOString(), src: 'tab', имя };
    for (const [ключ, значение] of Object.entries(данные)) {
      if (значение === undefined) continue;
      запись[ключ] = typeof значение === 'string' ? чисто(значение) : значение;
    }
    цепочка = цепочка.then(() => new Promise(готово => {
      try {
        chrome.storage.local.get(КЛЮЧ_ЖУРНАЛА, данные_ => {
          const было = Array.isArray(данные_ && данные_[КЛЮЧ_ЖУРНАЛА]) ? данные_[КЛЮЧ_ЖУРНАЛА] : [];
          const стало = [...было, запись].slice(-ЛИМИТ);
          try { chrome.storage.local.set({ [КЛЮЧ_ЖУРНАЛА]: стало }, готово); } catch (e) { готово(); }
        });
      } catch (e) { готово(); }
    }));
    return цепочка;
  };

  const прочитать = () => new Promise(готово => {
    try {
      chrome.storage.local.get(КЛЮЧ_ЖУРНАЛА, данные => готово((данные && данные[КЛЮЧ_ЖУРНАЛА]) || []));
    } catch (e) { готово([]); }
  });

  const очистить = () => new Promise(готово => {
    try { chrome.storage.local.set({ [КЛЮЧ_ЖУРНАЛА]: [], 'журнал_фона': [] }, готово); } catch (e) { готово(); }
  });

  const включить = включитьЛи => {
    включён = !!включитьЛи;
    return new Promise(готово => {
      try { chrome.storage.sync.set({ [КЛЮЧ_ФЛАГА]: !!включитьЛи }, готово); } catch (e) { готово(); }
    });
  };

  window.XCDebug = {
    событие,
    прочитать,
    очистить,
    включить,
    включён: () => включён,
    КЛЮЧ_ЖУРНАЛА,
    КЛЮЧ_ФЛАГА
  };
})();
