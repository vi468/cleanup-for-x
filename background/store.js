// ---------------------------------------------------------------------------
//  Схема хранилища расширения и её миграции.
//
//  Раньше ключи в chrome.storage.local жили как получится. Теперь есть номер
//  схемы: при старте worker проверяет его и приводит данные к текущему виду.
//  Заодно здесь лимит истории и выгрузка/загрузка данных одним файлом.
//
//  Данные приходят из storage и из файла пользователя, то есть могут быть
//  какими угодно. Поэтому всё прочитанное приводится к ожидаемому виду молча:
//  миграция не имеет права упасть на битой истории. Иначе номер схемы не
//  встанет, миграция будет повторяться после каждого старта worker'а, а
//  защищённые аккаунты останутся в неизвестном виде.
// ---------------------------------------------------------------------------
export const ВЕРСИЯ = 2;
export const ЛИМИТ_ИСТОРИИ = 20000;     // id на модуль; глубже — уже не история, а склад

const КЛЮЧ = 'схема';
const КЛЮЧИ_ЭКСПОРТА = ['история', 'защита', 'архив_списки', 'архив_репосты', 'архив_цитаты', 'архив_лайки'];

const получить = ключи => chrome.storage.local.get(ключи);
const записать = объект => chrome.storage.local.set(объект);

const этоObject = значение => !!значение && typeof значение === 'object' && !Array.isArray(значение);

/** Список: всё, что не массив, — пустой список; элементы — строки. */
const какСписок = значение => (Array.isArray(значение) ? значение.map(String) : []);

/**
 * Запись истории модуля. Бывает, что вместо { ids, ts } лежит просто массив id
 * (старый формат, правка руками) — приводим к схеме. Совсем не запись — null.
 */
const какЗапись = значение => {
  if (Array.isArray(значение)) return { ids: значение.map(String), ts: 0 };
  if (!этоObject(значение)) return null;
  return { ...значение, ids: какСписок(значение.ids) };
};

/** Подрезает запись истории до лимита. Возвращает { запись, обрезано }. */
const подрезать = значение => {
  const запись = какЗапись(значение);
  if (!запись) return { запись: null, обрезано: 0 };
  if (запись.ids.length <= ЛИМИТ_ИСТОРИИ) return { запись, обрезано: 0 };
  const лишних = запись.ids.length - ЛИМИТ_ИСТОРИИ;
  const былоОбрезано = Number(запись.обрезано) || 0;
  return {
    запись: {
      ...запись,
      ids: запись.ids.slice(-ЛИМИТ_ИСТОРИИ),
      обрезано: былоОбрезано + лишних
    },
    обрезано: лишних
  };
};

// Ники и id неприкасаемых: список, но одиночная строка тоже принимается —
// так данные не теряются, если список правили руками и он стал строкой.
const какЗащитаСписок = значение => {
  if (Array.isArray(значение)) return значение.map(String);
  if (typeof значение === 'string' && значение.trim()) return [значение];
  return [];
};

const уникальные = значения => [...new Set(значения.map(x => String(x).trim()).filter(Boolean))];

/**
 * Список неприкасаемых в том же виде, в каком его пишет shared/protect.js.
 * Массив или строка вместо объекта — это список ников (так правили руками);
 * null — данные не про защиту, трогать нечего.
 */
const какЗащита = значение => {
  if (Array.isArray(значение)) {
    return { ники: уникальные(значение.map(ник => ник.toLowerCase())), id: [] };
  }
  if (typeof значение === 'string') {
    return { ники: уникальные([значение.toLowerCase()]), id: [] };
  }
  if (!этоObject(значение)) return null;
  const ники = уникальные(какЗащитаСписок(значение.ники).map(ник => ник.toLowerCase()));
  const id = уникальные(какЗащитаСписок(значение.id));
  return { ники, id };
};

/** Приводит хранилище к текущей схеме. Возвращает { версия, была, обрезано }. */
export const мигрировать = async () => {
  const данные = await получить([КЛЮЧ]);
  const была = Number(данные[КЛЮЧ] || 1);
  if (была >= ВЕРСИЯ) return { версия: ВЕРСИЯ, была, обрезано: 0 };

  const всё = await получить(КЛЮЧИ_ЭКСПОРТА);
  let обрезано = 0;
  let изменилось = false;

  // --- история -----------------------------------------------------------
  const старшая = всё['история'];
  const история = этоObject(старшая) ? { ...старшая } : {};
  if (старшая !== undefined && !этоObject(старшая)) изменилось = true;  // был мусор

  for (const модуль of Object.keys(история)) {
    const было = история[модуль];
    const итог = подрезать(было);
    if (!итог.запись) {
      delete история[модуль];
      изменилось = true;
      continue;
    }
    // Не та форма записи (массив вместо { ids }) или не массив id — уже повод
    // записать историю заново: потребители читают только record.ids.
    if (Array.isArray(было) || !Array.isArray(было && было.ids) || итог.обрезано > 0) изменилось = true;
    обрезано += итог.обрезано;
    история[модуль] = итог.запись;
  }

  // --- неприкасаемые -----------------------------------------------------
  // Пишем только когда их правда нужно поправить: иначе миграция затирала бы
  // то, что попап мог сохранить, пока она читала storage.
  const защита = какЗащита(всё['защита']);
  let защитаНужно = false;
  if (защита && всё['защита'] !== undefined) {
    const было = всё['защита'];
    защитаНужно = !этоObject(было) ||
      !Array.isArray(было.ники) || !Array.isArray(было.id) ||
      защита.ники.length !== было.ники.length || защита.id.length !== было.id.length;
  }

  const изменения = { [КЛЮЧ]: ВЕРСИЯ };
  if (изменилось) изменения['история'] = история;
  if (защитаНужно) изменения['защита'] = защита;
  await записать(изменения);
  return { версия: ВЕРСИЯ, была, обрезано };
};

/** Снимок данных для файла: история, защита, загруженные архивы. */
export const экспорт = async () => {
  const данные = await получить(КЛЮЧИ_ЭКСПОРТА);
  return {
    приложение: 'Cleanup for X',
    версия: ВЕРСИЯ,
    когда: new Date().toISOString(),
    данные
  };
};

/** Загрузка снимка: списки объединяются, ничего не затирается. */
export const импорт = async снимок => {
  const данные = снимок && снимок.данные;
  // Файлы, выгруженные до 1.14.0, подписаны старым именем — их тоже принимаем.
  const ПОДПИСИ = ['Cleanup for X', 'X Cleaner'];
  if (!снимок || !ПОДПИСИ.includes(снимок.приложение) || !этоObject(данные)) {
    throw new Error('это не файл Cleanup for X');
  }

  const сейчас = await получить(КЛЮЧИ_ЭКСПОРТА);
  const итог = {};
  let добавленоЗащиты = 0;
  let добавленоИстории = 0;

  // защита: тот же вид, что у shared/protect.js; чужие типы в файле не роняют импорт
  const пришла = какЗащита(данные['защита']);
  if (пришла) {
    const было = какЗащита(сейчас['защита']) || { ники: [], id: [] };
    const ники = [...new Set([...было.ники, ...пришла.ники])];
    const id = [...new Set([...было.id, ...пришла.id])];
    добавленоЗащиты = (ники.length - было.ники.length) + (id.length - было.id.length);
    итог['защита'] = { ники, id };
  }

  // история: набор на модуль, старые данные остаются, новые добавляются
  const пришлаИстория = данные['история'];
  if (этоObject(пришлаИстория)) {
    const было = этоObject(сейчас['история']) ? сейчас['история'] : {};
    const новое = { ...было };
    for (const модуль of Object.keys(пришлаИстория)) {
      const чужая = какЗапись(пришлаИстория[модуль]);
      if (!чужая || !чужая.ids.length) continue;             // пустое не заводим
      const прежняя = какЗапись(было[модуль]);
      const набор = new Set(прежняя ? прежняя.ids : []);
      const до = набор.size;
      чужая.ids.forEach(id => набор.add(id));
      добавленоИстории += набор.size - до;
      новое[модуль] = подрезать({ ...чужая, ids: [...набор], ts: Date.now() }).запись;
    }
    итог['история'] = новое;
  }

  await записать(итог);
  return { добавленоЗащиты, добавленоИстории };
};
