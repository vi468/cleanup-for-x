/** GraphQL-вызов: перебирает известные queryId, пока не найдёт рабочий. */
const график = async (операция, переменные) => {
  let последний = { status: 0, body: '', reset: 0 };
  for (const qid of await qidДля(операция)) {
    let r;
    try {
      r = await fetch(`https://x.com/i/api/graphql/${qid}/${операция}`, {
        method: 'POST',
        credentials: 'include',
        headers: await заголовки({ 'content-type': 'application/json' }),
        body: JSON.stringify({ variables: переменные, queryId: qid })
      });
    } catch (e) {
      // Сеть отвалилась — другие queryId не помогут: пусть очередь встанет.
      return { status: 0, body: String(e && e.message || e), reset: 0 };
    }
    последний = await ответ(r);
    if (последний.status === 404) {
      // «Записи нет» (404 с телом) от смены queryId не зависит — перебор
      // запасных тут только жёг бы запросы.
      if (!пустой404(последний)) return последний;
      continue;
    }
    if (последний.status === 200) await запомнитьQid(операция, qid);
    return последний;
  }
  return последний;
};

