// --- сама очередь ---------------------------------------------------------
const идут = new Set();

// Запускаем цикл без await, но с ловлей отказа: иначе упавший шаг остался бы
// необработанным промисом — в консоли worker'а и нигде больше.
const запустить = (вид, темп) => {
  цикл(вид, темп).catch(ошибка => console.warn('[Cleanup for X] очередь', вид, 'упала:', ошибка));
};

const цикл = async (вид, темп) => {
  if (идут.has(вид)) return;
  идут.add(вид);

  // service worker засыпает без событий — раз в 20 секунд дёргаем дешёвый API,
  // чтобы его не выгрузили посреди очереди
  const пинг = setInterval(() => {
    try { chrome.runtime.getPlatformInfo(() => {}); } catch (e) {}
  }, 20000);

  const пакет = [];
  let подряд = 0;
  let подряд404 = 0;
  let подряд429 = 0;
  let паузаПосле = -1;   // на каком «сделано» уже отдохнули, чтобы не отдыхать дважды

  // Перед итоговым статусом дописываем историю: панель по этому статусу
  // перечитывает её и не должна увидеть неполную.
  const писатьПрогресс = async (правка, терминально) => {
    if (терминально) await дописатьИсторию(вид, пакет.splice(0));
    return поправить(вид, правка);
  };

  try {
    for (;;) {
      const состояние = await читатьСостояние(вид);
      if (!состояние.запущено) break;

      const элементы = await очередьВида(вид);
      if (состояние.курсор >= элементы.length) {
        // В живом режиме конец очереди — не конец работы: ждём, что подкинут ещё.
        await дописатьИсторию(вид, пакет.splice(0));
        await поправить(вид, с => {
          с.запущено = !!с.живой;
          с.статус = с.живой ? 'жду прокрутки' : 'готово';
        });
        break;
      }

      const id = элементы[состояние.курсор];
      let r;
      try { r = await ВИДЫ[вид].действие(id); }
      catch (e) { r = { status: 0, body: String(e && e.message || e), reset: 0 }; }

      let терминально = false;   // этот шаг останавливает очередь
      let ждать429 = 0;          // сколько ждать по лимиту X

      if (r.status === 200) {
        подряд = 0; подряд404 = 0; подряд429 = 0;
        пакет.push(id);
        if (пакет.length >= 10) await дописатьИсторию(вид, пакет.splice(0));

      } else if (r.status === 429) {
        // Лимит X: шаг не засчитываем и с места не двигаемся, «сделано» не растёт.
        подряд429 += 1;
        ждать429 = Math.min(15 * 60 * 1000,
          Math.max(5000, r.reset ? r.reset * 1000 - Date.now() + 1000 : 60000));
        терминально = подряд429 >= 5;

      } else if (r.status === 404) {
        // Пустое тело или HTML — это не «записи нет», а не тот маршрут.
        // Такие id нельзя запоминать в истории, иначе они «сделаны» навсегда.
        if (пустой404(r)) {
          подряд404 += 1;
          терминально = подряд404 >= 3;
        } else {
          подряд = 0; подряд404 = 0; подряд429 = 0;
          пакет.push(id);
        }

      } else {
        подряд += 1;
        терминально = r.status === 0 || r.status === 401 || r.status === 403 || подряд >= 5;
      }

      отладка({
        вид,
        шаг: 'ответ',
        id,
        код: r.status,
        тело: String(r.body || '').slice(0, 200),
        курсор: состояние.курсор,
        сделано: состояние.сделано,
        пропущено: состояние.пропущено
      });

      const свежее = await писатьПрогресс(с => {
        if (r.status === 200) {
          с.сделано = (с.сделано || 0) + 1;
          с.ошибок = 0;
          с.последняя = '';
          с.курсор = состояние.курсор + 1;
          // «пауза — лимит X» уже позади; но чужой «стоп» не перебиваем
          if (с.запущено) с.статус = 'работаю';

        } else if (r.status === 429) {
          с.последняя = `${id}: 429, пауза ${Math.round(ждать429 / 1000)} с`;
          с.статус = терминально ? 'остановлено: лимит X не отпускает' : 'пауза — лимит X';
          if (терминально) с.запущено = false;

        } else if (r.status === 404) {
          if (пустой404(r)) {
            с.ошибок = (с.ошибок || 0) + 1;
            с.последняя = `${id}: 404 без тела — похоже, сменился queryId`;
            if (терминально) {
              с.запущено = false;
              с.статус = 'остановлено: маршрут не тот (404)';
            }
          } else {
            с.пропущено = (с.пропущено || 0) + 1;
            с.курсор = состояние.курсор + 1;
          }

        } else {
          с.ошибок = (с.ошибок || 0) + 1;
          с.последняя = `${id}: ${r.status} ${r.body}`;
          if (r.status === 0 || r.status === 401 || r.status === 403) {
            с.запущено = false;
            с.статус = `остановлено: ${r.status || 'сеть'}`;
          }
          if (подряд >= 5) {
            с.запущено = false;
            с.статус = 'остановлено: 5 ошибок подряд';
          }
        }
      }, терминально);

      if (!свежее.запущено) break;

      if (r.status === 429) {
        await sleep(ждать429);
        continue;
      }

      // Долгая пауза каждые N шагов: X считает частоту, а не только число,
      // поэтому длинный проход выгоднее разбавлять. Отдыхаем один раз на
      // каждую достигнутую отметку, а не на каждой ошибке возле неё.
      if (состояние.каждые && свежее.сделано && состояние.пауза &&
          свежее.сделано % состояние.каждые === 0 && свежее.сделано !== паузаПосле) {
        паузаПосле = свежее.сделано;
        await поправить(вид, с => {
          с.статус = `пауза ${Math.round(состояние.пауза / 1000)} с после ${состояние.каждые}`;
        });
        await sleep(состояние.пауза);
      }

      await sleep(темп);
    }
  } finally {
    try { await дописатьИсторию(вид, пакет.splice(0)); } catch (e) {}
    clearInterval(пинг);
    идут.delete(вид);
  }
};

