/**
 * Приводит пачку id к работе: пустые, повторы внутри пачки и уже сделанное
 * отсекаются. Возвращает { принято: [...], отклонено: N } — по «отклонено»
 * вызывающая сторона видит, что пачка ушла не вся.
 */
const разобратьIds = (ids, занятые) => {
  const принято = [];
  const видели = new Set();
  let отклонено = 0;
  for (const сырой of ids || []) {
    const id = String(сырой == null ? '' : сырой).trim();
    if (!id || занятые.has(id) || видели.has(id)) { отклонено += 1; continue; }
    видели.add(id);
    принято.push(id);
  }
  return { принято, отклонено };
};

