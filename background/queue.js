// ---------------------------------------------------------------------------
//  Один движок на все «по одному запросу» действия: отписка, репосты, цитаты,
//  лайки, зависшие лайки (у них на один id идёт пара запросов). Работает в
//  service worker, без DOM и без вкладки: очередь лежит в
//  chrome.storage.local, поэтому закрытая вкладка и выгрузка worker её не рвут.
//
//  Состояние по каждому виду лежит отдельно:
//    задания/<вид>         — прогресс (курсор, счётчики, статус), пишется часто
//    задания_очередь/<вид> — сам список id, пишется один раз на запуск
//  Так очередь на 6 000 id не перезаписывается на каждом шаге.
//
//  Прогресс, очередь и найденные queryId держим ещё и в памяти worker'а (см.
//  «хранилище»): иначе на шаг уходило 3–4 чтения storage, из них чтение очереди
//  на тысячи элементов. Копия ничего не отменяет в storage — каждая запись туда
//  по-прежнему уходит, поэтому выгрузка worker'а не теряет ничего: после старта
//  копия просто прочитается заново.
//
//  Ответы X разбираются одинаково для всех видов:
//    200           — сделано, id в историю;
//    404 без тела  — не тот маршрут (сменился queryId), шаг не засчитываем;
//    404 с телом   — записи уже нет, в историю;
//    429           — пауза по x-rate-limit-reset (или минута), шаг не двигаем;
//    401/403/сеть  — стоп; 5 ошибок подряд — тоже стоп.
// ---------------------------------------------------------------------------
