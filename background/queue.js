export const начать = async ({ вид, ids = [], темп = 2000, каждые = 0, пауза = 0, живой = false }) => {
  if (!ВИДЫ[вид]) return { ok: false, ошибка: 'неизвестный вид задания' };

  // Проверку «уже запущено» и запись новой очереди делаем под замком: два
  // одновременных «Старт» иначе оба увидят простой и затрут очередь друг друга.
  const запуск = await подЗамком(КЛЮЧ, async () => {
    const текущее = await читатьСостояние(вид);
    if (текущее.запущено) return null;

    const сделано = сделаноизИстории(await читатьИсторию(), вид);
    const { принято, отклонено } = разобратьIds(ids, сделано);

    await заменитьОчередь(вид, принято);

    const новое = {
      ...пусто(),
      вид,
      всего: принято.length,
      запущено: true,
      статус: 'работаю',
      старт: Date.now(),
      темп,
      каждые,
      пауза,
      живой: !!живой
    };
    await писатьБезЗамка(вид, новое);
    отладка({ вид, шаг: 'старт', всего: принято.length, отклонено, темп, живой: !!живой });
    return { ...новое, ok: true, принято: принято.length, отклонено };
  });

  if (запуск) {
    запустить(вид, темп);
    return запуск;
  }

  // Пока проверяли, задание уже пошло: новые id не теряем, а дописываем в его
  // очередь — так повторное «Старт» из панели не отменяет уже сделанное.
  return { ...(await добавить({ вид, ids, темп, живой })), ужеЗапущено: true };
};

/** Дополнить живую очередь: страница подкидывает id по мере листания. */
export const добавить = async ({ вид, ids = [], темп = 0, живой = false, каждые = 0, пауза = 0, сила = false }) => {
  if (!ВИДЫ[вид]) return { ok: false, ошибка: 'неизвестный вид задания' };

  const пачка = (ids || []).map(String);
  let принято = 0;
  let отклонено = 0;
  let длина = 0;

  if (пачка.length) {
    // сила: страница видит карточку, а история говорит «сделано». Значит либо
    // карточка осталась в кэше, либо в историю когда-то попал чужой id — в
    // обоих случаях честнее спросить сервер заново, чем молча пропустить.
    const сделано = сила ? new Set() : сделаноизИстории(await читатьИсторию(), вид);
    const итог = await принятьВОчередь(вид, пачка, сделано);
    принято = итог.принято.length;
    отклонено = итог.отклонено;
    длина = итог.длина;
  }

  // Правка, а не снимок: идущий цикл в это время пишет сюда же курсор и
  // счётчики, и старый снимок вернул бы его на уже сделанные id.
  const состояние = await поправить(вид, с => {
    if (живой) с.живой = true;
    if (!с.старт) с.старт = Date.now();
    с.запущено = true;
    с.статус = 'работаю';
    if (темп) с.темп = темп;
    // Живая очередь может задать свой ритм: сбор со страницы идёт через
    // «добавить», а не через «начать», и длинные паузы тоже нужны.
    if (каждые) с.каждые = каждые;
    if (пауза) с.пауза = пауза;
    if (длина) с.всего = длина;
  });

  if (!идут.has(вид)) запустить(вид, состояние.темп || 1500);
  return { ...состояние, ok: true, принято, отклонено };
};

/** Листание закончилось: остаток дорабатываем и закрываем очередь. */
export const завершить = async вид => {
  отладка({ вид, шаг: 'листание закончено' });
  const элементы = await очередьВида(вид);
  const состояние = await поправить(вид, с => {
    с.живой = false;
    if (с.курсор >= элементы.length) {
      с.запущено = false;
      с.статус = 'готово';
    } else if (с.запущено) {
      с.статус = 'доделываю остаток';
    }
  });

  if (состояние.запущено && !идут.has(вид)) запустить(вид, состояние.темп || 1500);
  return состояние;
};

export const остановить = async вид => {
  отладка({ вид, шаг: 'стоп' });
  return поправить(вид, с => {
    с.запущено = false;
    с.статус = 'остановлено';
  });
};

export const продолжитьВсе = async () => {
  for (const вид of Object.keys(ВИДЫ)) {
    const состояние = await читатьСостояние(вид);
    if (состояние.запущено) запустить(вид, состояние.темп || 2000);
  }
};

export const проверить = async (вид, id) => {
  if (!ВИДЫ[вид]) return { ok: false, ошибка: 'неизвестный вид задания' };
  if (!id) return { ok: false, ошибка: 'не передан id' };
  return ВИДЫ[вид].действие(String(id));
};

// Формат, который X принимает в пути GraphQL: только буквы, цифры, дефис и
// подчёркивание, не короче десяти символов.
const QID_ФОРМАТ = /^[A-Za-z0-9_-]{10,}$/;

/** Вкладка нашла свежий queryId в бандлах — worker подхватит его на следующем шаге. */
export const установитьQid = async (операция, qid) => {
  // id приходит из бандлов страницы, то есть из чужого кода. Без проверки один
  // мусорный id отравил бы все запросы операции (и отдавал бы пустой 404).
  if (typeof операция !== 'string' || !Object.prototype.hasOwnProperty.call(QID_ПО_УМОЛЧАНИЮ, операция)) {
    return { ok: false, ошибка: 'неизвестная операция' };
  }
  const id = typeof qid === 'string' ? qid.trim() : '';
  if (!QID_ФОРМАТ.test(id)) return { ok: false, ошибка: 'queryId не похож на настоящий' };
  await запомнитьQid(операция, id);
  return { ok: true, операция, qid: id };
};
