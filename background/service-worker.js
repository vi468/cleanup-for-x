// ---------------------------------------------------------------------------
//  Фоновая часть расширения.
//
//  1) Держит тумблеры модулей в chrome.storage.sync и перезагружает открытые
//     вкладки X, когда состав включённых модулей меняется (единственная
//     перезагрузка: контент-скрипты сами страницу больше не трогают).
//  2) Крутит очередь заданий (background/queue.js): отписка, репосты, цитаты,
//     лайки, зависшие лайки. Живёт без вкладки, переживает выгрузку worker и
//     перезапуск браузера.
// ---------------------------------------------------------------------------
import * as очередь from './queue.js';
import * as хранилище from './store.js';

const ПО_УМОЛЧАНИЮ = { tweets: true, reposts: true, quotes: true, likes: true,
  ghostlikes: true, dms: true, unfollow: true };

// Числа из сообщений вкладки: мусор не должен попадать в темп очереди.
const число = (значение, поумолчанию) => {
  const н = Number(значение);
  return Number.isFinite(н) && н >= 0 ? н : поумолчанию;
};

const список = значение => (Array.isArray(значение) ? значение : []);

const выставитьЗначения = () => {
  chrome.storage.sync.get(null, данные => {
    const недостающие = Object.keys(ПО_УМОЛЧАНИЮ).filter(ид => (данные || {})[ид] === undefined);
    if (!недостающие.length) return;
    chrome.storage.sync.set(Object.fromEntries(недостающие.map(ид => [ид, ПО_УМОЛЧАНИЮ[ид]])));
  });
};

// Вкладка могла закрыться между query и reload — это не повод для отказа промиса.
const перезагрузитьВкладку = вкладка => {
  if (!вкладка || typeof вкладка.id !== 'number') return;
  try {
    const итог = chrome.tabs.reload(вкладка.id);
    if (итог && typeof итог.catch === 'function') итог.catch(() => {});
  } catch (e) { /* вкладки уже нет */ }
};

const перезагрузитьВкладки = () => {
  chrome.tabs.query({ url: ['https://x.com/*', 'https://twitter.com/*'] }, вкладки => {
    (вкладки || []).forEach(перезагрузитьВкладку);
  });
};

// Один и тот же подъём на все три входа: установка, старт браузера и обычный
// старт worker'а после выгрузки. Две копии этого кода успевали запустить
// очередь дважды, хотя цикл и сам себя защищает.
const поднять = ({ значения = false } = {}) => {
  if (значения) выставитьЗначения();
  хранилище.мигрировать().catch(ошибка => console.warn('[Cleanup for X] миграция не прошла:', ошибка));
  // service worker могли выгрузить посреди очереди — поднимаем её
  очередь.продолжитьВсе().catch(ошибка => console.warn('[Cleanup for X] очередь не поднялась:', ошибка));
};

chrome.runtime.onInstalled.addListener(() => поднять({ значения: true }));
chrome.runtime.onStartup.addListener(() => поднять({ значения: true }));

поднять();

// Панель отписки зовёт старые имена сообщений и ждёт старое имя счётчика.
const ПОД_СТАРЫМ_ИМЕНЕМ = { запущено: 'запущено', сделано: 'отписал', ошибок: 'ошибок',
  всего: 'всего', пропущено: 'пропущено', статус: 'статус', последняя: 'последняя' };

const дляСтаройПанели = состояние => {
  const итог = { ...состояние };
  for (const [новое, старое] of Object.entries(ПОД_СТАРЫМ_ИМЕНЕМ)) итог[старое] = состояние[новое];
  return итог;
};

chrome.runtime.onMessage.addListener((сообщение, отправитель, ответ) => {
  const тип = сообщение && сообщение.type;

  // Канал мог закрыться (попап закрыли) — ответ в него не должен ронять worker.
  const отправить = данные => {
    try { ответ(данные); } catch (e) { /* канал уже закрыт */ }
  };

  (async () => {
    try {
      if (тип === 'reload-x-tabs') {
        перезагрузитьВкладки();
        отправить({ ok: true });

      } else if (тип === 'jobs-start') {
        отправить(await очередь.начать({
          вид: сообщение.вид,
          ids: список(сообщение.ids),
          темп: число(сообщение.темп || сообщение.delayMs, 2000),
          каждые: число(сообщение.каждые, 0),
          пауза: число(сообщение.пауза, 0),
          живой: !!сообщение.живой
        }));

      } else if (тип === 'jobs-add') {
        отправить(await очередь.добавить({
          вид: сообщение.вид,
          ids: список(сообщение.ids),
          темп: число(сообщение.темп, 0),
          живой: !!сообщение.живой,
          каждые: число(сообщение.каждые, 0),
          пауза: число(сообщение.пауза, 0)
        }));

      } else if (тип === 'jobs-finish') {
        отправить(await очередь.завершить(сообщение.вид));

      } else if (тип === 'jobs-stop') {
        отправить(await очередь.остановить(сообщение.вид));

      } else if (тип === 'jobs-status') {
        отправить(await очередь.читатьСостояние(сообщение.вид));

      } else if (тип === 'jobs-all') {
        отправить(await очередь.читатьВсеСостояния());

      } else if (тип === 'jobs-test') {
        отправить(await очередь.проверить(сообщение.вид, сообщение.id));

      } else if (тип === 'set-qid') {
        // Свежий queryId из бандлов страницы. Формат проверяет очередь.
        отправить(await очередь.установитьQid(сообщение.операция, сообщение.qid));

      // --- старые имена: панель отписки ещё говорит на них ----------------
      } else if (тип === 'bg-unfollow-start') {
        отправить(дляСтаройПанели(await очередь.начать({
          вид: 'unfollow', ids: список(сообщение.ids), темп: число(сообщение.delayMs, 2000)
        })));

      } else if (тип === 'bg-unfollow-stop') {
        отправить(дляСтаройПанели(await очередь.остановить('unfollow')));

      } else if (тип === 'bg-unfollow-status') {
        отправить(дляСтаройПанели(await очередь.читатьСостояние('unfollow')));

      } else if (тип === 'bg-unfollow-test') {
        отправить(await очередь.проверить('unfollow', сообщение.id));

      } else {
        отправить({ ok: false, ошибка: 'неизвестный запрос' });
      }
    } catch (e) {
      отправить({ ok: false, ошибка: String(e && e.message || e) });
    }
  })();

  return true;                      // ответ будет асинхронным
});
