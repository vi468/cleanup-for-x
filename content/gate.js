// ---------------------------------------------------------------------------
//  Общий вход для всех модулей.
//
//  Настройки лежат в chrome.storage.sync (тумблеры в попапе расширения).
//  Каждый модуль регистрируется здесь и запускается только если он включён,
//  а при переключении тумблера фоновая часть перезагружает вкладки x.com —
//  поэтому «выключить» всегда означает «модуль больше не появится».
// ---------------------------------------------------------------------------
(() => {
  const XC = (window.__XC = window.__XC || {});
  window.XC = XC;                       // модули обращаются к нему по имени XC
  const ожидают = [];
  let настройки = null;
  let запущено = false;

  // Не включён — это только явное false. Ключа может не быть вовсе: модуль
  // добавили после того, как настройки уже сохранились, и выключенным он быть
  // не должен только из-за этого.
  XC.включён = id => (настройки ? настройки[id] !== false : true);
  XC.настройки = () => ({ ...(настройки || {}) });

  XC.модуль = (id, фабрика) => {
    const item = { id, фабрика };
    ожидают.push(item);
    // настройки могли прийти раньше, чем загрузился этот модуль
    if (настройки) запустить(item);
  };

  const запустить = item => {
    if (!XC.включён(item.id)) return;
    try {
      item.экземпляр = item.фабрика();
      (window.__XC_журнал = window.__XC_журнал || []).push({ id: item.id, ok: true });
    } catch (e) {
      (window.__XC_журнал = window.__XC_журнал || []).push({ id: item.id, ok: false, ошибка: String(e && e.message || e), стек: String(e && e.stack || '') });
      console.error(`Cleanup for X: модуль «${item.id}» не запустился`, e);
    }
  };

  const готово = () => {
    if (запущено) return;                 // второй раз модули не поднимаем
    запущено = true;
    ожидают.forEach(запустить);
  };

  // Запасной набор — «всё включено» по списку модулей из shared/modules.js.
  // Сам список живёт в одном месте; здесь только страховка на случай, если
  // настройки прочитать не удалось и modules.js не подгрузился.
  const поумолчанию = () => {
    const иды = (window.XCModules && window.XCModules.иды) ||
      ['tweets', 'reposts', 'quotes', 'likes', 'dms', 'unfollow'];
    return Object.fromEntries(иды.map(ид => [ид, true]));
  };

  const загрузить = () => {
    let выполнено = false;
    let сторож = null;
    const закончить = () => {
      if (выполнено) return;
      выполнено = true;
      if (сторож) clearTimeout(сторож);
      готово();
    };
    try {
      chrome.storage.sync.get(null, data => {
        настройки = data || {};
        закончить();
      });
    } catch (e) {
      // не расширение (например, скрипт запущен вручную) — работаем как раньше
      настройки = поумолчанию();
      закончить();
      return;
    }
    // Сторож: если колбэк хранилища не придёт (worker выгрузили, контекст
    // расширения устарел), модули не должны молча не появиться.
    сторож = setTimeout(() => {
      if (выполнено) return;
      if (!настройки) настройки = поумолчанию();
      закончить();
    }, 3000);
  };

  // Тумблер переключили в попапе — открытые вкладки перезагружает фон
  // (background/service-worker.js). Здесь только держим настройки свежими:
  // своя перезагрузка отсюда давала вторую перезагрузку поверх фоновой.
  try {
    chrome.storage.onChanged.addListener((changes, area) => {
      if (area !== 'sync') return;
      const свежие = Object.fromEntries(
        Object.entries(changes).map(([ключ, изменение]) => [ключ, изменение.newValue])
      );
      настройки = { ...(настройки || {}), ...свежие };
    });
  } catch (e) {}

  загрузить();
})();
