// Тест схемы хранилища: миграция, лимит истории, экспорт и импорт.
// Запуск: node test/store.test.js
import assert from 'node:assert/strict';

const хранилище = {};
globalThis.chrome = {
  storage: {
    local: {
      get: async ключи => {
        const список = Array.isArray(ключи) ? ключи : [ключи];
        const итог = {};
        список.forEach(ключ => { if (хранилище[ключ] !== undefined) итог[ключ] = хранилище[ключ]; });
        return итог;
      },
      set: async объект => { Object.assign(хранилище, объект); }
    }
  }
};

const магазин = await import('../background/store.js');
const { мигрировать, экспорт, импорт, ЛИМИТ_ИСТОРИИ, ВЕРСИЯ } = магазин;

// 1. история сверх лимита подрезается, схема ставится
{
  const много = Array.from({ length: ЛИМИТ_ИСТОРИИ + 500 }, (_, и) => String(и));
  хранилище['история'] = { likes: { ids: много, ts: 1 }, reposts: { ids: ['x'], ts: 1 } };
  const итог = await мигрировать();
  assert.equal(итог.версия, ВЕРСИЯ);
  assert.equal(итог.обрезано, 500);
  assert.equal(хранилище['схема'], ВЕРСИЯ);
  assert.equal(хранилище['история'].likes.ids.length, ЛИМИТ_ИСТОРИИ);
  assert.equal(хранилище['история'].likes.обрезано, 500);
  assert.deepEqual(хранилище['история'].reposts.ids, ['x'], 'короткая история не должна меняться');
  console.log('ок: миграция подрезает историю и ставит версию схемы');
}

// 2. повторная миграция ничего не делает
{
  const итог = await мигрировать();
  assert.equal(итог.обрезано, 0);
  console.log('ок: повторная миграция не трогает данные');
}

// 3. экспорт отдаёт узнаваемый снимок
{
  хранилище['защита'] = { ники: ['abc'], id: ['42'] };
  const снимок = await экспорт();
  assert.equal(снимок.приложение, 'Cleanup for X');
  assert.equal(снимок.версия, ВЕРСИЯ);
  assert.deepEqual(снимок.данные['защита'].ники, ['abc']);
  assert.ok(снимок.данные['история'], 'история должна попасть в снимок');
  console.log('ок: экспорт собирает снимок');
}

// 4. импорт объединяет, а не затирает
{
  хранилище['защита'] = { ники: ['abc'], id: [] };
  хранилище['история'] = { likes: { ids: ['1', '2'], ts: 1 } };
  const итог = await импорт({
    приложение: 'Cleanup for X',
    данные: {
      'защита': { ники: ['ABC', 'newone'], id: ['42'] },
      'история': { likes: { ids: ['2', '3'] }, reposts: { ids: ['r1'] } }
    }
  });
  assert.equal(итог.добавленоЗащиты, 2, 'newone и id 42');
  assert.equal(итог.добавленоИстории, 2, '3 и r1');
  assert.deepEqual(хранилище['защита'].ники.sort(), ['abc', 'newone']);
  assert.deepEqual(хранилище['история'].likes.ids.sort(), ['1', '2', '3']);
  assert.deepEqual(хранилище['история'].reposts.ids, ['r1']);
  console.log('ок: импорт объединяет защиту и историю');
}

// 5. чужой файл отвергается
{
  await assert.rejects(() => импорт({ приложение: 'Not Cleanup for X' }), /не файл Cleanup for X/);
  await assert.rejects(() => импорт(null), /не файл Cleanup for X/);
  await assert.rejects(() => импорт({ приложение: 'Cleanup for X', данные: 'мусор' }), /не файл Cleanup for X/);
  await assert.rejects(() => импорт({ приложение: 'Cleanup for X', данные: [] }), /не файл Cleanup for X/);
  console.log('ок: чужой файл не принимается');
}

// 5b. файл, выгруженный до переименования, принимается
{
  хранилище['защита'] = { ники: [], id: [] };
  const итог = await импорт({
    приложение: 'X Cleaner',
    данные: { 'защита': { ники: ['legacy'], id: [] } }
  });
  assert.equal(итог.добавленоЗащиты, 1);
  console.log('ок: файл со старым именем принимается');
}

// 6. битая история не роняет миграцию: мусор в ids, записи нет, массив вместо записи
{
  хранилище['схема'] = undefined;
  хранилище['история'] = {
    likes: { ids: 42, ts: 1 },             // вместо списка — число
    dms: 'мусор',                          // вместо записи — строка
    reposts: ['r1', 'r2'],                 // старый формат: просто массив
    quotes: null                           // пусто
  };
  const итог = await мигрировать();
  assert.equal(итог.версия, ВЕРСИЯ);
  assert.equal(хранилище['схема'], ВЕРСИЯ, 'номер схемы должен встать даже на битых данных');
  assert.deepEqual(хранилище['история'].likes.ids, [], 'не-массив ids должен стать пустым списком');
  assert.equal(хранилище['история'].dms, undefined, 'мусорная запись должна уехать');
  assert.equal(хранилище['история'].quotes, undefined, 'пустая запись должна уехать');
  assert.deepEqual(хранилище['история'].reposts.ids, ['r1', 'r2'], 'старый массив должен стать записью');
  console.log('ок: миграция переживает битую историю и приводит её к схеме');
}

// 7. битая история целиком (строка вместо объекта) тоже не роняет миграцию
{
  хранилище['схема'] = undefined;
  хранилище['история'] = 'совсем не объект';
  const итог = await мигрировать();
  assert.equal(итог.версия, ВЕРСИЯ);
  assert.deepEqual(хранилище['история'], {}, 'мусорная история должна стать пустой');
  console.log('ок: мусорная история заменяется пустой');
}

// 8. битая защита приводится к виду protect.js, аккаунты не теряются
{
  хранилище['схема'] = undefined;
  хранилище['защита'] = { ники: 'ABC', id: [42, '43', 42] };
  await мигрировать();
  assert.deepEqual(хранилище['защита'].ники, ['abc'], 'строка вместо списка ников не должна теряться');
  assert.deepEqual(хранилище['защита'].id, ['42', '43'], 'id — строки, без повторов');
  console.log('ок: битая защита приводится к схеме');
}

// 9. импорт не падает на кривых списках в файле и не заводит пустых записей
{
  хранилище['схема'] = undefined;
  хранилище['защита'] = { ники: ['abc'], id: [] };
  хранилище['история'] = { likes: { ids: ['1'], ts: 1 } };
  const итог = await импорт({
    приложение: 'Cleanup for X',
    данные: {
      'защита': { ники: { не: 'список' }, id: '42' },
      'история': { likes: { ids: 'мусор' }, tweets: { ids: [] }, reposts: ['r1'] }
    }
  });
  assert.equal(итог.добавленоЗащиты, 1, 'одиночный id строкой в файле должен приняться, объект — нет');
  assert.equal(итог.добавленоИстории, 1, 'старый массив id в файле должен приняться');
  assert.deepEqual(хранилище['защита'].ники, ['abc']);
  assert.deepEqual(хранилище['защита'].id, ['42']);
  assert.deepEqual(хранилище['история'].likes.ids, ['1']);
  assert.equal(хранилище['история'].tweets, undefined, 'пустой модуль не должен появляться');
  assert.deepEqual(хранилище['история'].reposts.ids, ['r1']);
  console.log('ок: импорт переживает кривые списки в файле');
}

// 10. импорт режет историю по лимиту и не теряет свежие id
{
  хранилище['схема'] = ВЕРСИЯ;
  хранилище['история'] = { likes: { ids: ['старый'], ts: 1 } };
  const много = Array.from({ length: ЛИМИТ_ИСТОРИИ + 10 }, (_, и) => 'н' + и);
  const итог = await импорт({ приложение: 'Cleanup for X', данные: { 'история': { likes: { ids: много } } } });
  assert.equal(итог.добавленоИстории, ЛИМИТ_ИСТОРИИ + 10);
  assert.equal(хранилище['история'].likes.ids.length, ЛИМИТ_ИСТОРИИ, 'история должна подрезаться по лимиту');
  assert.equal(хранилище['история'].likes.ids[хранилище['история'].likes.ids.length - 1], 'н' + (ЛИМИТ_ИСТОРИИ + 9),
    'подрезать надо старое, а не свежее');
  assert.equal(хранилище['история'].likes.обрезано, 11, 'счётчик обрезанного должен учитывать и старый id');
  console.log('ок: импорт подрезает историю по лимиту');
}

console.log('все тесты прошли');
